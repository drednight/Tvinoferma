/* Цвет класса — стабильный хеш от названия, чтобы аватары не прыгали между макетами */
TV.clsColor = function (cls) {
  const hues = {
    Воин: 18,
    Маг: 268,
    Жрец: 150,
    Стрелок: 92,
    Бард: 200,
    Призрак: 300,
    Лучник: 130,
    Страж: 210
  };
  return hues[cls] || ((cls || '').length * 37) % 360;
};

TV.clsInitials = function (cls) {
  if (!cls) return '?';
  return cls.slice(0, 2);
};
